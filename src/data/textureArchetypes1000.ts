// Preserve the anchor families while giving every variant its own identifier.
function catalogSignature(index: number) {
  if (index < 2) return index === 0 ? 'studio-anchor' : 'studio-anchor-2';
  if (index < 4) return index === 2 ? 'signal-anchor' : 'signal-anchor-2';
  return `atelier-${String(index - 3).padStart(4, '0')}`;
}

